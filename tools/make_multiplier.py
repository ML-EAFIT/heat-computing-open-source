#!/usr/bin/env python3
"""Write a circuit problem file: an n x m-bit array multiplier p = a * b with p clamped.

Clamping the product runs the multiplier backwards, so the chip searches for factors
(docs/09_programming.md, same construction as examples/factor6.json and section 21.3
of the factorization monograph in data/).

    python3 tools/make_multiplier.py 143                 # smallest a, b widths that can hold it
    python3 tools/make_multiplier.py 143 --bits 4 4 -o examples/factor143.json

Gates: AND partial products, then rows added with half adders (XOR + AND) and full
adders (2 XOR, 2 AND, 1 OR), the gadgets of model/pgates.GADGETS.
"""
import argparse
import json
import sys


def multiplier(na, nb):
    gates = []
    a = [f"a{i}" for i in range(na)]
    b = [f"b{j}" for j in range(nb)]
    k = [0]

    def wire(prefix):
        k[0] += 1
        return f"{prefix}{k[0]}"

    def half(x, y):
        s, c = wire("s"), wire("c")
        gates.append(["XOR", x, y, s])
        gates.append(["AND", x, y, c])
        return s, c

    def full(x, y, z):
        t, s = wire("t"), wire("s")
        u, v, c = wire("u"), wire("v"), wire("c")
        gates.append(["XOR", x, y, t])
        gates.append(["XOR", t, z, s])
        gates.append(["AND", x, y, u])
        gates.append(["AND", t, z, v])
        gates.append(["OR", u, v, c])
        return s, c

    # partial products pp[j][i] = a_i b_j, weight i + j
    pp = [[f"pp{i}_{j}" for i in range(na)] for j in range(nb)]
    for j in range(nb):
        for i in range(na):
            gates.append(["AND", a[i], b[j], pp[j][i]])
    # acc[w] = wire of weight w in the running sum
    acc = {i: pp[0][i] for i in range(na)}
    for j in range(1, nb):
        carry = None
        for i in range(na):
            w = i + j
            x = pp[j][i]
            if w in acc:
                if carry is None:
                    acc[w], carry = half(acc[w], x)
                else:
                    acc[w], carry = full(acc[w], x, carry)
            elif carry is not None:
                acc[w], carry = half(x, carry)
            else:
                acc[w] = x
        acc[na + j] = carry
    p = [acc[w] for w in range(na + nb)]
    return a, b, p, gates


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("product", type=int)
    ap.add_argument("--bits", type=int, nargs=2, metavar=("NA", "NB"),
                    help="input widths (default: smallest equal widths with 2^(na+nb) > product)")
    ap.add_argument("--beta", type=float, default=2.0)
    ap.add_argument("--sps", type=int, default=32, help="sweeps per annealing step (16 steps)")
    ap.add_argument("-o", "--out", default=None)
    o = ap.parse_args()
    N = o.product
    if o.bits:
        na, nb = o.bits
    else:
        na = nb = max(2, (N.bit_length() + 1) // 2)
    if N >= 1 << (na + nb):
        raise SystemExit(f"{N} needs {N.bit_length()} product bits, {na}x{nb} gives {na + nb}")
    a, b, p, gates = multiplier(na, nb)
    # give the product wires readable names p0..p{n-1} (renaming, no extra p-bits)
    outs = [f"p{w}" for w in range(len(p))]
    ren = dict(zip(p, outs))
    gates = [[g[0]] + [ren.get(x, x) for x in g[1:]] for g in gates]
    fact = [(x, N // x) for x in range(2, N) if N % x == 0 and x < 1 << na and N // x < 1 << nb]
    note = (f"expected answers (a, b): {fact}" if fact else
            f"WARNING: {N} has no factorization a*b with 1 < a < 2^{na}, 1 < b < 2^{nb}"
            + (" (it is prime)" if all(N % x for x in range(2, int(N ** 0.5) + 1)) else ""))
    spec = {
        "type": "circuit",
        "comment": f"{na}x{nb}-bit array multiplier p = a*b run backwards: clamp p = {N} "
                   f"({N:0{na + nb}b}); {note}. Generated by tools/make_multiplier.py",
        "inputs": a + b,
        "outputs": outs,
        "gates": gates,
        "clamp": {w: (N >> k) & 1 for k, w in enumerate(outs)},
        "show": {"a": a, "b": b, "p": outs},
        "beta": o.beta,
        "schedule": {"beta_start": o.beta / 4, "beta_end": o.beta, "sweeps_per_step": o.sps},
    }
    text = json.dumps(spec, indent=1)
    if o.out:
        open(o.out, "w").write(text + "\n")
    else:
        sys.stdout.write(text + "\n")
    print(f"{na}x{nb} multiplier, {len(gates)} gates; {note}", file=sys.stderr)


if __name__ == "__main__":
    main()
