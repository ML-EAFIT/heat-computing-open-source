#!/usr/bin/env python3
"""Write build/case_top_<case>.v: rtl/top.v whose power-on program is a model case.

The weights, biases, visit order and beta schedule of model/vectors/<case>/
become the RAM initial values, so the run button samples that case with no
host attached. Used by `make case CASE=factor6` (docs/05): the button runs the
2x2-bit multiplier backwards on product 6 and the LEDs show a0 a1 b0 b1 p0.
A wrapper top is needed because yosys cannot pass string parameters with
-chparam (docs/07).
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "model"))
import cases as cs           # noqa: E402
import export_vectors as ev  # noqa: E402

name = sys.argv[1]
c = {k["name"]: k for k in cs.all_cases()}[name]
sc = ev.case_schedule(c)
n = c["n"]
iw = max(1, (n - 1).bit_length())
aw = 8 + n.bit_length() + 1
hb = min(n, 12)
v = f"../model/vectors/{name}"
demo = 256 if sc["mode"] == 2 else 128
pt = ""
if c.get("ladder"):
    # parallel tempering: the button runs DEMO_SWEEPS rounds (K sweeps each) of the rung-0 replica
    lad = sum(b << (8 * k) for k, b in enumerate(c["ladder"]))
    pt = f", .TEMPER_K({len(c['ladder'])}), .TEMPER_LADDER(32'h{lad:08x})"
    demo = 64
open(f"build/case_top_{name}.v", "w").write(f"""// generated by fpga/case_wrapper.py: top.v programmed with case {name}
`default_nettype none
module case_top (
    input  wire       clk,
    input  wire       btn_rst_n,
    input  wire       btn_run_n,
    input  wire       uart_rxd,
    output wire       uart_txd,
    output wire [5:0] led
);
top #(
    .N({n}), .IW({iw}), .AW({aw}), .HIST_BITS({hb}), .WFRAC({c['wfrac']}), .DEMO_SWEEPS({demo}),
    .W_FILE("{v}/weights.hex"), .H_FILE("{v}/bias.hex"), .O_FILE("{v}/order.hex"),
    .T_FILE("{v}/beta_table.hex"),
    .DEF_MODE(2'd{sc['mode']}), .DEF_BETA0(8'd{sc['beta_start']}), .DEF_BETA1(8'd{sc['beta_end']}),
    .DEF_DELTA(8'd{sc['delta']}), .DEF_SPS(16'd{sc['sps']}){pt}
) top_inst (
    .clk(clk), .btn_rst_n(btn_rst_n), .btn_run_n(btn_run_n),
    .uart_rxd(uart_rxd), .uart_txd(uart_txd), .led(led)
);
endmodule
""")
print(f"build/case_top_{name}.v: N={n} mode={sc['mode']} demo_sweeps={demo}")
