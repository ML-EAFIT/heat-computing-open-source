#!/usr/bin/env python3
"""Write build/pmode_top_<tag>.v: rtl/pmode_top.v with a power-on p-mode program.

  pmode_wrapper.py <case>       model/vectors/pm_<case>/ (well, tilt, pair, chain4)
  pmode_wrapper.py fit <M>      M sites, zero RAMs (fit study)
A wrapper top is needed because yosys cannot pass string parameters with
-chparam (docs/07).
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "model"))
import fixed as fx           # noqa: E402
import pmode as pm           # noqa: E402

if sys.argv[1] == "fit":
    m = int(sys.argv[2])
    tag = f"fit{m}"
    c = dict(lamq=32, k=4, sig=1448)
    files = 'A_FILE(""), .H_FILE(""), .X_FILE("")'
else:
    tag = sys.argv[1]
    c = pm.case(tag)
    m = c["m"]
    v = f"../model/vectors/pm_{tag}"
    files = f'A_FILE("{v}/a.hex"), .H_FILE("{v}/h.hex"), .X_FILE("{v}/x0.hex")'
mw = fx.clog2(m)
open(f"build/pmode_top_{tag}.v", "w").write(f"""// generated by fpga/pmode_wrapper.py: pmode_top.v, {tag}
`default_nettype none
module pmode_wrap (
    input  wire       clk,
    input  wire       btn_rst_n,
    input  wire       btn_run_n,
    input  wire       uart_rxd,
    output wire       uart_txd,
    output wire [5:0] led
);
pmode_top #(
    .M({m}), .MW({mw}), .LAM(8'd{c['lamq']}), .KSHIFT(4'd{c['k']}), .SIG(16'd{c['sig']}),
    .{files}
) pmode_top_inst (
    .clk(clk), .btn_rst_n(btn_rst_n), .btn_run_n(btn_run_n),
    .uart_rxd(uart_rxd), .uart_txd(uart_txd), .led(led)
);
endmodule
""")
print(f"build/pmode_top_{tag}.v: M={m} lambda_q={c['lamq']} k={c['k']} sig={c['sig']}")
