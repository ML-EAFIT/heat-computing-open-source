#!/usr/bin/env python3
"""Write build/sweep_top_<N>.v: rtl/top.v with N p-bits and zero-initialised RAMs."""
import sys

n = int(sys.argv[1])
iw = max(1, (n - 1).bit_length())
aw = 8 + n.bit_length() + 1
hb = min(n, 12)
b = "build"
open(f"{b}/zw_{n}.hex", "w").write("00\n" * (1 << (2 * iw)))
open(f"{b}/zh_{n}.hex", "w").write("00\n" * (1 << iw))
open(f"{b}/zo_{n}.hex", "w").write("".join(f"{i:x}\n" for i in range(1 << iw)))
open(f"{b}/sweep_top_{n}.v", "w").write(f"""// generated by fpga/sweep_wrapper.py: top.v with N = {n}
`default_nettype none
module sweep_top (
    input  wire       clk,
    input  wire       btn_rst_n,
    input  wire       btn_run_n,
    input  wire       uart_rxd,
    output wire       uart_txd,
    output wire [5:0] led
);
top #(
    .N({n}), .IW({iw}), .AW({aw}), .HIST_BITS({hb}),
    .W_FILE("{b}/zw_{n}.hex"), .H_FILE("{b}/zh_{n}.hex"), .O_FILE("{b}/zo_{n}.hex")
) top_inst (
    .clk(clk), .btn_rst_n(btn_rst_n), .btn_run_n(btn_run_n),
    .uart_rxd(uart_rxd), .uart_txd(uart_txd), .led(led)
);
endmodule
""")
