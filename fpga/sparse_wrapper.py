#!/usr/bin/env python3
"""Write build/sparse_top_<tag>.v: rtl/top.v with SPARSE = 1 (sparse_array.v).

  sparse_wrapper.py N P D            empty lane RAMs (programmed over UART), fit study
  sparse_wrapper.py N P D <case>     power-on program = model/vectors/sp_<case>_p<P>/
  sparse_wrapper.py N P D <case> noise   same with NOISE_CTL = 1 ('Y' noise options)

LW = clog2(N/P) rounds per sweep, enough for two-colourable graphs whose colour
blocks are multiples of P (the G-pattern grids); other graphs may need LW + 1
(fpga/host.py checks). Up counters live in BSRAM (UP_RAM = 1). A wrapper top is
needed because yosys cannot pass string parameters with -chparam (docs/07).
"""
import math
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "model"))
import cases as cs           # noqa: E402
import export_vectors as ev  # noqa: E402
import fixed as fx           # noqa: E402

n, p, d = (int(x) for x in sys.argv[1:4])
case = sys.argv[4] if len(sys.argv) > 4 else None
noise = len(sys.argv) > 5 and sys.argv[5] == "noise"
iw = fx.clog2(n)
dw = fx.clog2(d)
lw = fx.clog2(math.ceil(n / p))
aw = 8 + fx.clog2(d + 1) + 1
hb = min(n, 12)
tag = f"{n}_p{p}" + (f"_{case}" if case else "") + ("_noise" if noise else "")
extra = 'NODE_PREFIX(""), .NBR_PREFIX(""), .ROUNDS(1)'
if case:
    c = {x["name"]: x for x, _ in cs.sparse_cases()}[case]
    lay = ev.sparse_layout(c, p)
    assert c["n"] <= n and lay["D"] <= d and lay["R"] <= (1 << lw), "case does not fit this build"
    assert lay["DW"] == dw, "slot address width of the case files must match D"
    sc = ev.case_schedule(c)
    v = f"../model/vectors/sp_{case}_p{p}"
    extra = (f'NODE_PREFIX("{v}/node_e"), .NBR_PREFIX("{v}/nbr_e"), .ROUNDS({lay["R"]}),\n'
             f'    .T_FILE("{v}/beta_table.hex"), .DEF_MODE(2\'d{sc["mode"]}), '
             f'.DEF_BETA0(8\'d{sc["beta_start"]}), .DEF_BETA1(8\'d{sc["beta_end"]}),\n'
             f'    .DEF_DELTA(8\'d{sc["delta"]}), .DEF_SPS(16\'d{sc["sps"]})')
    if lay["LW"] != lw:
        # the case files are sized for the case's own round count
        raise SystemExit(f"case uses LW={lay['LW']}, build LW={lw}: re-export or change P")
open(f"build/sparse_top_{tag}.v", "w").write(f"""// generated by fpga/sparse_wrapper.py: top.v SPARSE, N = {n}, P = {p}, D = {d}{', case ' + case if case else ''}
`default_nettype none
module sparse_top (
    input  wire       clk,
    input  wire       btn_rst_n,
    input  wire       btn_run_n,
    input  wire       uart_rxd,
    output wire       uart_txd,
    output wire [5:0] led
);
top #(
    .N({n}), .IW({iw}), .AW({aw}), .HIST_BITS({hb}), .UP_RAM(1),
    .SPARSE(1), .P({p}), .D({d}), .DW({dw}), .LW({lw}), .NOISE_CTL({int(noise)}),
    .{extra}
) top_inst (
    .clk(clk), .btn_rst_n(btn_rst_n), .btn_run_n(btn_run_n),
    .uart_rxd(uart_rxd), .uart_txd(uart_txd), .led(led)
);
endmodule
""")
print(f"build/sparse_top_{tag}.v: N={n} P={p} D={d} IW={iw} DW={dw} LW={lw} AW={aw}")
